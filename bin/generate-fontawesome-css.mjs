/**
 * Generates a minimal, self-hosted Font Awesome stylesheet.
 *
 * Instead of shipping FontAwesome's ~400KB all.min.css (and hitting cdnjs on every
 * request), this script:
 *   1. Scans the codebase for `fa-*` icon classes that are actually used.
 *   2. Emits only those glyph rules, plus the shared @font-face declarations.
 *   3. Copies the woff2 subsets into public/fonts/.
 *
 * Output: resources/css/generated/fontawesome.css (imported by app.css).
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const faDir = resolve(root, 'node_modules/@fortawesome/fontawesome-free');
const outDir = resolve(root, 'resources/css/generated');
const publicFonts = resolve(root, 'public/fonts');

const ALIASES = {
    // FontAwesome 5 names still used in older markup.
    'check-circle': 'circle-check',
    columns: 'table-columns',
};

/** Collect icon class names + style used anywhere in the project. */
function collectUsedIcons() {
    const dirs = ['themes', 'modules', 'resources', 'app'].map((d) => resolve(root, d)).join(' ');
    const raw = execSync(
        `grep -rhoE "fa-(solid|regular|brands)[[:space:]]+fa-[a-z0-9-]+" ${dirs} 2>/dev/null || true`,
        { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }
    );

    const used = new Set();
    for (const line of raw.split('\n')) {
        const m = line.trim().match(/fa-(solid|regular|brands)\s+(fa-[a-z0-9-]+)/);
        if (m) used.add(`${m[1]}|${m[2].replace(/^fa-/, '')}`);
    }
    return used;
}

/**
 * FontAwesome 7 ships one metadata file (icon-families.json) keyed by icon name.
 * `svgs.classic` tells us which styles exist for the icon.
 */
function loadIconFamilies() {
    return JSON.parse(readFileSync(resolve(faDir, 'metadata/icon-families.json'), 'utf8'));
}

function build() {
    mkdirSync(outDir, { recursive: true });
    mkdirSync(publicFonts, { recursive: true });

    const used = collectUsedIcons();
    const families = loadIconFamilies();

    const rules = [];
    const missing = [];

    for (const entry of used) {
        const [style, rawName] = entry.split('|');
        const name = ALIASES[rawName] ?? rawName;
        const icon = families[name];

        if (!icon || !icon.unicode) {
            missing.push(name);
            continue;
        }

        const styles = icon.svgs?.classic ?? {};
        const hasStyle = style === 'brands' ? Boolean(styles.brands) : Boolean(styles[style]);
        if (!hasStyle) {
            // Style mismatch (e.g. `fa-regular` on a solid-only icon): fall back to solid.
            if (!styles.solid) {
                missing.push(name);
                continue;
            }
        }

        rules.push({ name, unicode: icon.unicode, style: hasStyle ? style : 'solid' });
    }

    let css = `/* AUTO-GENERATED by bin/generate-fontawesome-css.mjs — do not edit. */

@font-face {
    font-family: 'Font Awesome 6 Free';
    font-style: normal;
    font-weight: 900;
    font-display: block;
    src: url('/fonts/fa-solid-900.woff2') format('woff2');
}

@font-face {
    font-family: 'Font Awesome 6 Free';
    font-style: normal;
    font-weight: 400;
    font-display: block;
    src: url('/fonts/fa-regular-400.woff2') format('woff2');
}

@font-face {
    font-family: 'Font Awesome 6 Brands';
    font-style: normal;
    font-weight: 400;
    font-display: block;
    src: url('/fonts/fa-brands-400.woff2') format('woff2');
}

/* Base classes (mirrors FontAwesome 7's own base layer). */
.fa {
    font-family: var(--fa-style-family, 'Font Awesome 6 Free');
    font-weight: var(--fa-style, 900);
}

.fas,
.far,
.fab,
.fa-solid,
.fa-regular,
.fa-brands,
.fa {
    -moz-osx-font-smoothing: grayscale;
    -webkit-font-smoothing: antialiased;
    display: var(--fa-display, inline-block);
    font-style: normal;
    font-variant: normal;
    line-height: 1;
    text-rendering: auto;
}

.fas::before,
.far::before,
.fab::before,
.fa-solid::before,
.fa-regular::before,
.fa-brands::before,
.fa::before {
    content: var(--fa);
}

/* Family + WEIGHT per style. The weight is what selects the right font file:
   solid glyphs only exist in the 900 face, so the solid classes must request 900
   or the browser falls back to regular and renders tofu. */
.fa-classic,
.fas,
.fa-solid {
    font-family: 'Font Awesome 6 Free';
    font-weight: 900;
}

.far,
.fa-regular {
    font-family: 'Font Awesome 6 Free';
    font-weight: 400;
}

.fa-brands,
.fab {
    font-family: 'Font Awesome 6 Brands';
    font-weight: 400;
}

/* Legacy v4 aliases still present in some markup. */
.fa-solid,
.fas {
    --fa-style-family: 'Font Awesome 6 Free';
    --fa-style: 900;
}

`;

    const seen = new Set();
    for (const rule of rules) {
        const key = `${rule.style}|${rule.name}`;
        if (seen.has(key)) continue;
        seen.add(key);

        const selector = rule.style === 'brands' ? '.fa-brands' : rule.style === 'regular' ? '.fa-regular' : '.fa-solid';

        // Metadata gives hex without leading zeros (e.g. "f0e7"). The glyph must
        // be emitted as `\f0e7` — padding to 4 digits, no extra prefix.
        const code = rule.unicode.toLowerCase().padStart(4, '0');

        css += `${selector}.fa-${rule.name}::before { content: "\\${code}"; }\n`;

        // FontAwesome 7 resolves glyphs through `--fa`; expose it too so markup
        // using the modern variable mechanism keeps working.
        css += `${selector}.fa-${rule.name} { --fa: "\\${code}"; }\n`;
    }

    writeFileSync(resolve(outDir, 'fontawesome.css'), css);

    for (const file of ['fa-solid-900.woff2', 'fa-regular-400.woff2', 'fa-brands-400.woff2']) {
        const src = resolve(faDir, 'webfonts', file);
        if (existsSync(src)) copyFileSync(src, resolve(publicFonts, file));
    }

    return { icons: seen.size, bytes: css.length, missing };
}

const result = build();
console.log(
    `[fontawesome] ${result.icons} glyphs → ${(result.bytes / 1024).toFixed(1)} KB, woff2 self-hosted in public/fonts`
);
if (result.missing.length) {
    console.log(`[fontawesome] not found in metadata (check names): ${result.missing.join(', ')}`);
}
