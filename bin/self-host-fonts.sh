#!/usr/bin/env bash
# Download the Latin and Latin Extended faces, then atomically replace the CSS.
# Existing assets remain usable if any request or subset validation fails.
set -euo pipefail
project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
python3 - "$project_root" <<'PY'
import os
import pathlib
import re
import subprocess
import sys
import tempfile

root = pathlib.Path(sys.argv[1])
fonts = root / 'public/fonts'
stylesheet = root / 'resources/css/generated/fonts.css'
fonts.mkdir(parents=True, exist_ok=True)
stylesheet.parent.mkdir(parents=True, exist_ok=True)
user_agent = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36'
families = (
    ('Plus+Jakarta+Sans', 'Plus Jakarta Sans', 'plus-jakarta-sans', '400;500;600;700;800'),
    ('Google+Sans+Code', 'Google Sans Code', 'google-sans-code', '400;500;700'),
)
lines = ['/* AUTO-GENERATED by bin/self-host-fonts.sh — do not edit. */', '']

with tempfile.TemporaryDirectory(prefix='.fonts-', dir=fonts) as temporary:
    staged = pathlib.Path(temporary)
    for family, display_name, slug, weights in families:
        css = subprocess.check_output([
            'curl', '-fsSL', '-A', user_agent,
            f'https://fonts.googleapis.com/css2?family={family}:wght@{weights}&display=swap',
        ], text=True)
        faces = re.findall(r'/\*\s*(latin(?:-ext)?)\s*\*/\s*(@font-face\s*\{[^}]*\})', css)
        if not any(subset == 'latin' for subset, _ in faces):
            raise RuntimeError(f'{display_name}: Latin subset is missing; existing assets were preserved')
        for subset, face in faces:
            def property_value(name):
                match = re.search(rf'{name}:\s*([^;]+);', face)
                if not match:
                    raise RuntimeError(f'{display_name}: missing {name}')
                return match.group(1).strip()

            url = re.search(r'url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)', face)
            if not url:
                raise RuntimeError(f'{display_name}: unsupported font source')
            weight = property_value('font-weight')
            style = property_value('font-style')
            unicode_range = property_value('unicode-range')
            if not re.fullmatch(r'\d+(?:\s+\d+)?', weight) or style not in ('normal', 'italic'):
                raise RuntimeError(f'{display_name}: unsupported font style or weight')
            filename = f'{slug}-{weight.replace(" ", "-")}-{subset}.woff2'
            destination = staged / filename
            subprocess.run(['curl', '-fsSL', '-o', str(destination), url.group(1)], check=True)
            if destination.read_bytes()[:4] != b'wOF2':
                raise RuntimeError(f'{display_name}: invalid WOFF2 download')
            lines.append(f'''@font-face {{
    font-family: '{display_name}';
    font-style: {style};
    font-weight: {weight};
    font-display: swap;
    src: url('/fonts/{filename}') format('woff2');
    unicode-range: {unicode_range};
}}''')
        print(f'[fonts] {display_name}: {len(faces)} face(s) self-hosted')
    candidate = staged / 'fonts.css'
    candidate.write_text('\n\n'.join(lines) + '\n')
    # All requests and validation succeeded before replacing any current asset.
    for font in staged.glob('*.woff2'):
        os.replace(font, fonts / font.name)
    os.replace(candidate, stylesheet)
print(f'[fonts] wrote {stylesheet.relative_to(root)}')
PY
