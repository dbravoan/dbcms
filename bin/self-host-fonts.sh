#!/usr/bin/env bash
#
# Self-hosts the two project fonts (Plus Jakarta Sans + Google Sans Code).
#
# Downloads only the `latin` (+ `latin-ext`) woff2 subsets from Google Fonts and
# writes them to public/fonts/, then generates resources/css/generated/fonts.css
# with @font-face rules using `font-display: swap`. Run once at setup/deploy; the
# output is committed-free (regenerated on demand) and imported by resources/css/app.css.
#
# Usage: bash bin/self-host-fonts.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_FONTS="${ROOT}/public/fonts"
OUT_CSS="${ROOT}/resources/css/generated/fonts.css"
UA="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"

mkdir -p "${OUT_FONTS}" "$(dirname "${OUT_CSS}")"

tmp_css="$(mktemp)"

{
    echo "/* AUTO-GENERATED by bin/self-host-fonts.sh — do not edit. */"
    echo
} > "${OUT_CSS}"

fetch_family() {
    local family="$1"          # e.g. Plus+Jakarta+Sans
    local slug="$2"            # e.g. plus-jakarta-sans
    local weights="$3"         # e.g. 400;500;600;700;800

    local css
    css="$(curl -fsSL -A "${UA}" "https://fonts.googleapis.com/css2?family=${family}:wght@${weights}&display=swap")"

    # Split the stylesheet per @font-face block and keep latin / latin-ext only.
    python3 - "$css" "$slug" "$OUT_FONTS" "$OUT_CSS" <<'PY'
import re, sys, subprocess, os

css, slug, out_fonts, out_css = sys.argv[1:5]
blocks = re.split(r'(?=@font-face)', css)
kept = []

for block in blocks:
    if '@font-face' not in block:
        continue
    # Subset comment precedes the block, e.g. /* latin */
    m_subset = re.search(r'/\*\s*([a-z0-9-]+)\s*\*/', block)
    subset = m_subset.group(1) if m_subset else 'unknown'
    if subset not in ('latin', 'latin-ext'):
        continue

    url = re.search(r'url\((https://[^)]+\.woff2)\)', block)
    if not url:
        continue

    weight = re.search(r'font-weight:\s*(\d+)', block)
    style = re.search(r'font-style:\s*(\w+)', block)
    unicode = re.search(r'unicode-range:\s*([^;]+);', block)
    weight = weight.group(1) if weight else '400'
    style = style.group(1) if style else 'normal'

    fname = f"{slug}-{weight}-{subset}.woff2"
    dest = os.path.join(out_fonts, fname)

    if not os.path.exists(dest):
        subprocess.run(['curl', '-fsSL', '-o', dest, url.group(1)], check=True)

    kept.append((subset, style, weight, unicode.group(1).strip() if unicode else None, fname))

# Merge @font-face by (style, weight, subset) preserving unicode-range.
families = {
    'plus-jakarta-sans': ('Plus Jakarta Sans', 'sans-serif'),
    'google-sans-code': ('Google Sans Code', 'monospace'),
}
display_name, fallback = families.get(slug, (slug, 'sans-serif'))

lines = []
for subset, style, weight, unicode_range, fname in kept:
    lines.append(f"""@font-face {{
    font-family: '{display_name}';
    font-style: {style};
    font-weight: {weight};
    font-display: swap;
    src: url('/fonts/{fname}') format('woff2');{f'''
    unicode-range: {unicode_range};''' if unicode_range else ''}
}}""")

with open(out_css, 'a') as fh:
    if lines:
        fh.write('\n'.join(lines) + '\n\n')

print(f"[fonts] {display_name}: {len(kept)} face(s) self-hosted")
PY
}

fetch_family "Plus+Jakarta+Sans" "plus-jakarta-sans" "400;500;600;700;800"
fetch_family "Google+Sans+Code" "google-sans-code" "400;500;700"

echo "[fonts] wrote $(wc -l < "${OUT_CSS}") lines -> ${OUT_CSS}"
ls -la "${OUT_FONTS}"
